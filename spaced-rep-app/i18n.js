/*
 * The catalog in the reader's language: the table and the one function that
 * reads it. Catalog only, the owner's call, 4 November 2026: a game page stands
 * on its own by concept and is not loaded with this, so nothing a game draws may
 * call tr() without asking whether it is there -- see explainSilence in speech.js.
 *
 * What stays in English on the screen, by the same call: the lists of languages,
 * the name of the app, the names of the games with the "Continue" and "Coming soon"
 * that go with them on a tile, and "updated" on the mark, which is drawn by hand.
 *
 * Only languages a machine translates at the level of a native writer, and none
 * written right to left. Arabic and Hebrew are not left out for their words: the
 * catalog is laid out by hand in lefts and rights, down to arrows aimed at single
 * buttons, and a mirrored screen is its own piece of work. Hindi and the smaller
 * languages can join by adding a block here: nothing else knows the list.
 *
 * One file and not one per language, because the switch has to be immediate, on
 * the press, and a script fetched on demand is a screen in the old language for
 * however long that takes. The whole table is smaller than the word list.
 *
 * Numbers that change the words around them are `{ one, few, many, other }`, read
 * through Intl.PluralRules; a form a language does not have is simply absent. What
 * goes into `{name}` is put in as it is, because some of it is markup: strings here
 * are this file's own, and nothing somebody typed passes through them. Quotes are
 * typographic for that reason as well: some strings end up inside an attribute.
 *
 * A key missing from a language reads as English, and a key missing from English
 * too reads as the fallback the caller gave. A half-translated screen is better
 * than a broken one, and that is what a new string costs until it is translated.
 */
