function tr(key, vars, fallback) {
    const own = UI_STRINGS[tr.now][key];
    const found = own !== undefined ? own : UI_STRINGS.en[key];

    if (found === undefined) return fallback !== undefined ? fallback : key;

    let text = found;

    if (typeof found !== 'string') {
        const form = new Intl.PluralRules(tr.now).select(vars.n);

        text = found[form] || found.other;
    }

    return vars ? text.replace(/\{(\w+)\}/g, (all, name) => (name in vars ? vars[name] : all)) : text;
}

tr.now = 'en';

tr.has = (tag) => Object.prototype.hasOwnProperty.call(UI_STRINGS, tag);

tr.langs = () => Object.keys(UI_STRINGS);

// The interface a language leads to: itself where there is one, and English.
tr.forLang = (tag) => (tr.has(tag) ? tag : 'en');

// lang on the page as well, because the browser reads it: uppercase in Turkish
// keeps its dotted İ only if it knows the page is Turkish, and a font for Han
// characters is chosen by it too.
tr.use = (tag) => {
    tr.now = tr.forLang(tag);
    document.documentElement.lang = tr.now;
};

// A slant is how the strip of help cards tells itself from the page, and it is
// a Latin habit: Chinese, Japanese and Korean have no italic, and what the browser
// does in its place is lean the characters over, which reads as a fault.
tr.italic = () => (['ja', 'ko', 'zh'].includes(tr.now) ? 'normal' : 'italic');

